#: Every place flattened, keyed by the label the form submits.
PLACES: dict[str, dict] = {}
for _group, _rows in PLACE_GROUPS:
    for _city, _country, _lat, _lng in _rows:
        _label = f"{_city}, {_country}"
        PLACES[_label.casefold()] = {
            "label": _label,
            "city": _city,
            "country": _country,
            "latitude": _lat,
            "longitude": _lng,
        }

#: Default map centre (Nairobi) used when nobody on the map is near the viewer.
DEFAULT_CENTRE = {"latitude": 1.2921, "longitude": 36.8219}


def find_place(label: str) -> dict | None:
    """Return the canonical place for a submitted label, or None."""
    if not label:
        return None
    return PLACES.get(label.strip().casefold())
